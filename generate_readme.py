#!/usr/bin/env python3
"""Generate README.md for vxime/engineering-invariants.

Sources:
  1. https://vxi.me/invariants/index.json  (canonical case list; zh titles, article URLs)
  2. cases.yaml                            (hand-maintained EN enrichment overlay)
  3. probes/                               (a probe link is emitted only if the file exists)

Usage:
  python3 generate_readme.py [--index /path/to/index.json] [--out README.md]

The sync workflow runs this automatically; do not edit README.md by hand.
"""
import argparse
import json
import os
import sys
import urllib.request

BASE = os.path.dirname(os.path.abspath(__file__))
INDEX_URL = "https://vxi.me/invariants/index.json"

CATEGORY_ORDER = [
    ("state-lifecycle", "01. State Machine & Lifecycle Tears", "状态机与生命周期撕裂",
     "Rejected states, protocol errors, or incomplete reviews leaking across handoff, admission gates, or retry boundaries."),
    ("sample-denominator", "02. Statistical Denominators & Sample Bias", "统计分母与样本偏差",
     "When inclusion rules, dedup, or the effective sample count change, a metric can shift even if the formula looks the same."),
    ("trust-permissions", "03. Trust Boundaries & Permission Escapes", "信任边界与权限逃逸",
     "What a tool returns, a command guard, or a dependency authorization actually covers may be narrower than intuition."),
    ("temporal-batch-boundary", "04. Temporal Boundaries & Batch Ordering", "时序边界与批次顺序",
     "Same-timestamp row order and truncated-batch end markers can be misread as real causality or batch completeness."),
]


def load_yaml(path):
    try:
        import yaml  # type: ignore
        with open(path, encoding="utf-8") as f:
            return yaml.safe_load(f)
    except ImportError:
        # Minimal fallback: parse the simple cases.yaml structure by hand.
        data = {"cases": {}}
        cur = None
        with open(path, encoding="utf-8") as f:
            for line in f:
                s = line.rstrip("\n")
                if s.startswith("  ") and s.rstrip().endswith(":") and not s.startswith("    "):
                    cur = s.strip()[:-1]
                    data["cases"][cur] = {}
                elif s.startswith("    ") and cur and ":" in s:
                    k, v = s.strip().split(":", 1)
                    data["cases"][cur][k.strip()] = v.strip().strip('"')
        return data


def fetch_index(path_or_url):
    if path_or_url.startswith("http"):
        req = urllib.request.Request(path_or_url, headers={"User-Agent": "engineering-invariants-sync/1.0"})
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read().decode("utf-8"))
    with open(path_or_url, encoding="utf-8") as f:
        return json.load(f)


def probe_link(slug):
    for ext in (".py", ".mjs", ".sh"):
        name = slug + ext
        if os.path.exists(os.path.join(BASE, "probes", name)):
            return f"[`probes/{name}`](./probes/{name})"
    return "—"


def en_post_url(article_url):
    # https://vxi.me/posts/<slug>/ -> https://vxi.me/en/posts/<slug>/
    return article_url.replace("https://vxi.me/posts/", "https://vxi.me/en/posts/")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--index", default=INDEX_URL)
    ap.add_argument("--out", default=os.path.join(BASE, "README.md"))
    args = ap.parse_args()

    index = fetch_index(args.index)
    overlay = load_yaml(os.path.join(BASE, "cases.yaml"))["cases"]

    by_group = {}
    for case in index["cases"]:
        by_group.setdefault(case["group_id"], []).append(case)

    lines = []
    A = lines.append
    A("# Engineering Invariants & Counter-Example Probes")
    A("")
    A("Deterministic reproducers, synthetic counter-examples, and verification receipts")
    A("for **AI coding agents, LLM inference engines, and quantitative market microstructure**.")
    A("")
    A("> Full interactive atlas & multilingual notes: **[vxi.me/invariants](https://vxi.me/invariants/)**")
    A("> ([English](https://vxi.me/en/invariants/) · [简体中文](https://vxi.me/invariants/) · [日本語](https://vxi.me/ja/invariants/))")
    A("")
    A("Each case pins the upstream version/commit it was verified against. Probes are")
    A("stdlib-only, self-contained, and runnable with a single command — no API keys,")
    A("no network, no real market data. Honest scope notes live in the linked articles:")
    A("a probe models the *mechanism*, it does not re-run the upstream engine.")
    A("")
    A("_This README is generated by `generate_readme.py` from the canonical case index; do not edit by hand._")
    A("")

    for gid, en_title, zh_title, desc in CATEGORY_ORDER:
        A(f"## {en_title} ({zh_title})")
        A(f"*{desc}*")
        A("")
        A("| System / Version | Failure Mode & Counter-Example | Standalone Probe | Evidence & Full Analysis |")
        A("| :--- | :--- | :--- | :--- |")
        for case in by_group.get(gid, []):
            slug = case["slug"]
            ov = overlay.get(slug, {})
            system = ov.get("system", "—")
            summary = ov.get("en_summary", case["article_title"])
            probe = probe_link(slug)
            links = [f"[📄 EN]({en_post_url(case['article_url'])})",
                     f"[中文]({case['article_url']})"]
            if case.get("markdown_url"):
                links.append(f"[md]({case['markdown_url']})")
            if case.get("evidence_url"):
                links.append(f"[🧾 JSON]({case['evidence_url']})")
            A(f"| **{system}** | {summary} | {probe} | {' · '.join(links)} |")
        A("")

    A("## Contributing a probe")
    A("")
    A("See [`probes/README.md`](./probes/README.md) for the probe contract: stdlib-only,")
    A("one-command runnable, honest docstring stating what is *not* covered.")
    A("")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {args.out} ({len(by_group)} groups)")


if __name__ == "__main__":
    sys.exit(main())
