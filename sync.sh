#!/usr/bin/env bash
# Sync engineering-invariants with the canonical vxi.me invariants index.
# - Downloads the latest index.json
# - Downloads every evidence/*.json the index references (only those that exist upstream)
# - Regenerates README.md
# Safe to run repeatedly; commits only when something changed.
set -euo pipefail
cd "$(dirname "$0")"

echo "== fetch index =="
curl -fsSL --max-time 30 "https://vxi.me/invariants/index.json" -o /tmp/ei-index.json

echo "== fetch evidence =="
mkdir -p evidence
python3 - <<'EOF'
import json, urllib.request, os
d = json.load(open('/tmp/ei-index.json'))
for c in d['cases']:
    u = c.get('evidence_url')
    if not u:
        continue
    name = u.rsplit('/', 1)[-1]
    dest = os.path.join('evidence', name)
    try:
        req = urllib.request.Request(u, headers={'User-Agent': 'engineering-invariants-sync/1.0'})
        with urllib.request.urlopen(req, timeout=30) as r:
            data = r.read()
        open(dest, 'wb').write(data)
        print(f"OK {name} ({len(data)} bytes)")
    except Exception as e:
        print(f"SKIP {name}: {e}")
EOF

echo "== regenerate README =="
python3 generate_readme.py --index /tmp/ei-index.json

echo "== verify probes still run =="
for p in probes/*.py; do
  python3 "$p" >/dev/null || { echo "PROBE FAILED: $p"; exit 1; }
done
for p in probes/*.mjs; do
  [ -e "$p" ] || continue
  node --test "$p" >/dev/null 2>&1 || { echo "PROBE FAILED: $p"; exit 1; }
done
echo "all probes pass"

echo "== detect cases missing probes =="
python3 - <<'EOF'
import json, os
d = json.load(open('/tmp/ei-index.json'))
missing = []
for c in d['cases']:
    slug = c['slug']
    has = any(os.path.exists(os.path.join('probes', slug + ext)) for ext in ('.py', '.mjs', '.sh'))
    if not has:
        missing.append((slug, c['article_title'], c['article_url']))
lines = ["# Probes TODO", "",
         "Cases in the canonical index that have no standalone probe yet.",
         "A probe must be stdlib-only, one-command runnable, and verified before commit",
         "(see probes/README.md). This file is regenerated by sync.sh — do not edit by hand.", ""]
if missing:
    for slug, title, url in missing:
        lines.append(f"- [ ] `{slug}` — [{title}]({url})")
else:
    lines.append("All cases have probes. 🎉")
open('PROBES_TODO.md', 'w').write("\n".join(lines) + "\n")
print(f"{len(missing)} cases missing probes")
EOF

if git diff --quiet && git status --porcelain | grep -q . ; then
  echo "untracked files only, nothing to commit"
elif git diff --quiet; then
  echo "no changes"
else
  git config user.email >/dev/null 2>&1 || git config user.email "vxime-bot@users.noreply.github.com"
  git config user.name >/dev/null 2>&1 || git config user.name "vxime-bot"
  git add -A
  git commit -m "chore(sync): refresh from vxi.me invariants index" \
    -m "Auto-sync: index.json, evidence/*.json, regenerated README.md."
  echo "committed"
fi
